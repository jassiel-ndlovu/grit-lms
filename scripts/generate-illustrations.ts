/**
 * npx tsx scripts/generate-illustrations.ts [path/to/Illustrations]
 *
 * Builds src/components/illustrations/generated/ from the owner's local copy
 * of the Open Peeps pack (CC0) and copies the chosen Transhumans PNGs (CC0)
 * into public/illustrations/. The source folder defaults to
 * ~/Documents/Illustrations and can also be set with ILLUSTRATIONS_SRC.
 *
 * Each SVG goes through `npx svgo` with scripts/illustrations/svgo.config.mjs
 * (svgo is not a project dependency), then becomes one React module, so a page
 * only pulls in the illustrations it renders.
 */

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

const SRC =
  process.argv[2] ?? process.env.ILLUSTRATIONS_SRC ?? path.join(os.homedir(), "Documents", "Illustrations");
const PEEPS = path.join(SRC, "Open-Peeps", "Flat Assets", "Flat Assets", "Templates");
const ROOT = path.resolve(__dirname, "..");
const OUT = path.join(ROOT, "src", "components", "illustrations", "generated");
const PUBLIC_OUT = path.join(ROOT, "public", "illustrations");
const SVGO_CONFIG = path.join(__dirname, "illustrations", "svgo.config.mjs");

/** Semantic name -> Open Peeps template. Busts become avatar-01..NN in this order. */
const SCENES: Record<string, string> = {
  "empty-courses": "Sitting/peep-sitting-9.svg",
  "empty-lessons": "Sitting/peep-sitting-2.svg",
  "empty-tests": "Standing/peep-standing-6.svg",
  "empty-submissions": "Standing/peep-standing-4.svg",
  "nothing-to-grade": "Sitting/peep-sitting-12.svg",
  "calendar-empty": "Sitting/peep-sitting-1.svg",
  "inbox-empty": "Sitting/peep-sitting-6.svg",
  "search-no-results": "Standing/peep-standing-5.svg",
  "onboarding-welcome": "Sitting/peep-sitting-15.svg",
  "onboarding-profile": "Standing/peep-standing-1.svg",
  "onboarding-courses": "Standing/peep-standing-26.svg",
  "success-submitted": "Standing/peep-standing-12.svg",
  "not-found": "Standing/peep-standing-22.svg",
  error: "Standing/peep-standing-16.svg",
};
const BUSTS = [
  6, 8, 10, 11, 13, 14, 17, 19, 26, 31, 33, 34, 37, 38, 39, 43, 46, 47, 51, 57, 59, 63, 66, 76, 78, 79, 87, 93, 96,
  99, 100, 102,
];
/** Public name -> Transhumans file. Raster, so they cannot follow the theme. */
const SPOTS: Record<string, string> = {
  "spot-study": "Growth-Study.png",
  "spot-school-run": "School-Run-Innocent.png",
  "spot-team": "Team-Cooperation.png",
  "spot-celebrate": "Chaos-Good-Dance.png",
};

const pascal = (name: string) => name.replace(/(^|-)(\w)/g, (_, __, c: string) => c.toUpperCase());
const JSX_ATTRS: Record<string, string> = {
  "fill-rule": "fillRule",
  "clip-rule": "clipRule",
  "stroke-width": "strokeWidth",
  "stroke-linecap": "strokeLinecap",
  "stroke-linejoin": "strokeLinejoin",
  "xlink:href": "href",
};

const entries: { name: string; source: string }[] = [
  ...Object.entries(SCENES).map(([name, file]) => ({ name, source: file })),
  ...BUSTS.map((n, i) => ({ name: `avatar-${String(i + 1).padStart(2, "0")}`, source: `Bust/peep-${n}.svg` })),
];

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "nexa-illustrations-"));
const tmpIn = path.join(tmp, "in");
const tmpOut = path.join(tmp, "out");
fs.mkdirSync(tmpIn);
let before = 0;
for (const { name, source } of entries) {
  const file = path.join(PEEPS, source);
  before += fs.statSync(file).size;
  fs.copyFileSync(file, path.join(tmpIn, `${name}.svg`));
}

const svgo = spawnSync("npx", ["--yes", "svgo", "--quiet", "--config", `"${SVGO_CONFIG}"`, "-f", `"${tmpIn}"`, "-o", `"${tmpOut}"`], {
  shell: true,
  stdio: "inherit",
});
if (svgo.status !== 0) throw new Error("svgo failed");

fs.rmSync(OUT, { recursive: true, force: true });
fs.mkdirSync(OUT, { recursive: true });
let after = 0;
const table: string[] = [];
for (const { name, source } of entries) {
  const svg = fs.readFileSync(path.join(tmpOut, `${name}.svg`), "utf8").trim();
  after += Buffer.byteLength(svg);
  const match = svg.match(/^<svg([^>]*)>([\s\S]*)<\/svg>$/);
  const viewBox = match?.[1].match(/viewBox="([^"]+)"/)?.[1];
  if (!match || !viewBox) throw new Error(`${name}: unexpected svgo output`);
  if (/<(style|script|image|text)\b/.test(match[2])) throw new Error(`${name}: unexpected element`);
  const body = match[2].replace(/([a-z:-]+)=/g, (attr, key: string) => (JSX_ATTRS[key] ? `${JSX_ATTRS[key]}=` : attr));
  if (/\s[a-z]+[-:][a-z]+=/.test(body)) throw new Error(`${name}: unmapped attribute`);
  fs.writeFileSync(
    path.join(OUT, `${name}.tsx`),
    `// Generated by scripts/generate-illustrations.ts from Open Peeps ${source} (CC0). Do not edit.\n` +
      `import { Illustration, type IllustrationProps } from "../illustration";\n\n` +
      `export default function ${pascal(name)}(props: IllustrationProps) {\n` +
      `  return (\n    <Illustration viewBox="${viewBox}" {...props}>\n      ${body}\n    </Illustration>\n  );\n}\n`,
  );
  table.push(`| \`${name}\` | Open Peeps \`Templates/${source}\` |`);
}

const sceneNames = Object.keys(SCENES);
const avatarNames = entries.filter((e) => e.name.startsWith("avatar-")).map((e) => e.name);
fs.writeFileSync(
  path.join(OUT, "registry.ts"),
  `// Generated by scripts/generate-illustrations.ts. Do not edit.\n` +
    `// Loaders only: nothing is bundled until a loader is called.\n\n` +
    `export const scenes = {\n${sceneNames.map((n) => `  "${n}": () => import("./${n}"),`).join("\n")}\n} as const;\n\n` +
    `export type SceneName = keyof typeof scenes;\n\n` +
    `export const avatars = [\n${avatarNames.map((n) => `  () => import("./${n}"),`).join("\n")}\n] as const;\n\n` +
    `export const AVATAR_COUNT = ${avatarNames.length};\n`,
);

fs.mkdirSync(PUBLIC_OUT, { recursive: true });
for (const [name, file] of Object.entries(SPOTS)) {
  fs.copyFileSync(path.join(SRC, "Transhumans", file), path.join(PUBLIC_OUT, `${name}.png`));
  table.push(`| \`${name}\` | Transhumans \`${file}\` (PNG) |`);
}
fs.rmSync(tmp, { recursive: true, force: true });

const kb = (n: number) => `${(n / 1024).toFixed(1)} KB`;
console.log(`${entries.length} SVGs: ${kb(before)} -> ${kb(after)} (${Math.round((1 - after / before) * 100)}% smaller)`);
console.log(table.join("\n"));
