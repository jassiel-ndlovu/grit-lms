/**
 * The one interface all money moves through (docs/revamp/a/design/04-payments.md,
 * section 2). Discounts, commission and split shares are computed in Nexa
 * first; the provider only sees final amounts. Client-safe types only.
 */

export type Cents = number; // integer ZAR cents

export type ProviderId = "PAYSTACK" | "PAYFAST";

export type ProviderStatus = "SUCCEEDED" | "FAILED" | "ABANDONED" | "PENDING";

export type NormalisedEvent = {
  dedupeKey: string;
  type: "charge.succeeded" | "charge.failed" | "refund.processed" | "refund.failed" | "dispute.opened" | "other";
  /** The raw provider event name, e.g. "charge.success". */
  providerType: string;
  reference: string | null;
  raw: unknown;
};

export interface PaymentProvider {
  readonly id: ProviderId;
  capabilities(): { multiSplit: boolean; variableCharge: boolean; refunds: boolean; eft: boolean };

  createCustomer(input: { email: string; name: string; metadata: Record<string, string> }): Promise<{ customerCode: string }>;

  initializeCheckout(input: {
    /** Payment.reference, generated by Nexa. */
    reference: string;
    email: string;
    amountCents: Cents;
    callbackUrl: string;
    channels?: Array<"card" | "eft">;
    /** The remainder goes to Nexa. */
    splits?: Array<{ subaccountCode: string; shareCents: Cents }>;
    feeBearer?: "PLATFORM" | "PAYEES_PROPORTIONAL";
    /** Ids only, no personal data. */
    metadata: Record<string, string>;
  }): Promise<{ authorizationUrl: string; reference: string }>;

  chargeAuthorization(input: {
    authorizationCode: string;
    email: string;
    amountCents: Cents;
    reference: string;
    metadata: Record<string, string>;
  }): Promise<{ status: "SUCCEEDED" | "FAILED" | "PENDING"; gatewayMessage?: string }>;

  createSubaccount(input: {
    businessName: string;
    bankCode: string;
    accountNumber: string;
    contactEmail: string;
    description: string;
  }): Promise<{ subaccountCode: string; accountName?: string }>;

  verifyTransaction(reference: string): Promise<{
    status: ProviderStatus;
    amountCents: Cents;
    currency: "ZAR";
    feeCents?: Cents;
    channel?: string;
    paidAt?: Date;
    authorization?: { code: string; reusable: boolean; brand: string; last4: string; expMonth: number; expYear: number };
  }>;

  refund(input: { reference: string; amountCents?: Cents; reason: string; idempotencyKey: string }): Promise<{
    providerRefundId: string;
    status: "PENDING" | "PROCESSED" | "FAILED";
  }>;

  listBanks(): Promise<Array<{ code: string; name: string }>>;

  resolveAccount(input: { bankCode: string; accountNumber: string; idNumber?: string }): Promise<{ accountName: string } | null>;

  /** Throws InvalidSignatureError. */
  verifyWebhook(rawBody: string, headers: Headers): NormalisedEvent;

  /** Reconciliation only. */
  listTransactions(input: { from: Date; to: Date }): Promise<Array<{ reference: string; status: string; amountCents: Cents }>>;
}

export class InvalidSignatureError extends Error {
  constructor() {
    super("Invalid webhook signature");
    this.name = "InvalidSignatureError";
  }
}

/** A provider call failed. `code` maps to the contract's PROVIDER_ERROR. */
export class ProviderError extends Error {
  readonly code = "PROVIDER_ERROR" as const;
  constructor(message: string, readonly httpStatus?: number) {
    super(message);
    this.name = "ProviderError";
  }
}
